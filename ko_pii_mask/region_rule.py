CHANGE_AFTER = re.compile(r"^\s?(?:으로|로)\s?(?:주소\s?)?(?:변경|바꿔|수정)")
ADDR_CONTEXT = re.compile(r"주소|등록지|거주지|주소지|전입|전출")
#: 지명이 사람의 위치가 아니라 물건·직장·시설의 위치다("과수원이 영천에 있는데", "예산에 있는 요양병원", "이전 직장 소재지 구미").
THING_BEFORE = re.compile(r"(?:밭|땅|토지|과수원|논|임야|건물|공장|매장|가게|회사|사무실|창고|산소|묘소|상가|빌딩|직장|사업장|지점|학교|병원|본사|근무지)"
                          r"\s?(?:이|가|은|는|도|의)?\s?(?:소재지|주소|위치)?\s?(?:[:：]\s?)?$")
THING_AFTER = re.compile(r"^\s?(?:에|에서)\s?있는\s?[가-힣]{0,6}(?:병원|요양병원|요양원|공장|매장|지점|센터|학교|회사|사무실|가게|식당|카페|호텔|"
                         r"토지|땅|밭|과수원|건물|창고|대리점|협력업체|현장)")
#: 사람을 가리키는 말이 같은 절 안에 있어야 하는 약한 서술.
#: "근처·쪽"은 현재 위치를 말하는 서술이 바로 붙을 때만("나 지금 연남동 근처야"). "포항 쪽 도로가", "익산역 근처 칼국수집"은 일반 언급.
WEAK_AFTER = re.compile(r"^\s?(?:(?:근처|부근|쪽)(?=\s?(?:이에요|예요|인데|이야|야|이라|라서|입니다|이고|에\s?있|에서\s?(?:대기|기다)))\s?)?" + _JOSA
                        + r"\s?(?:집|자택|숙소|있[가-힣]|와\s?있|가\s?있|"
                        r"내려가|내려와|내려갑|내려오|올라가|올라와|올라갑|올라오|다녀|통근|출퇴근|통학|"
                        r"이에요|예요|인데|이고|입니다|이야|야(?![가-힣])|이지|이니까|이라서|이잖|잖아|이었|였)")
#: 지명 바로 앞의 거주·출신 단서. 서식 칸 이름("출생지: ", "현 거주: ", "소재지: ", "거처 ")과 높임 관형("거주하시는", "계신").
_FIELD = (r"(?:(?:현재\s?|현\s?|실\s?|등록\s?|기존\s?|이전\s?|새\s?|변경\s?)?(?:거주지|거주\s?지역|거주|주거지|거처|주소지|주소|소재지|체류지|"
          r"출생지|출신지|출신|본적지|본적|등록지|전출지|전입지|전입\s?예정지|이전지|고향|본가|친정|시댁|처가|외가|자택|이사\s?갈\s?곳|"
          r"사는\s?곳|사는\s?데)|현재(?=\s?[:：]))")
STRONG_BEFORE = re.compile(r"(?<![가-힣])(?:" + _FIELD + r"\s?(?:이|은|는|가|도|로)?\s?(?:[:：\-–—]\s?)?"
                           r"|(?:거주하[가-힣]{0,3}|거주\s?중이?[가-힣]{0,2}|계시는|계신|사는|사시는|살던|살았던|살고\s?있는|살고\s?계신|지내는|지내시는|"
                           r"머무는|태어나고\s?자란|태어난|자란|자라온|이사\s?(?:갈|가실|간|온|오신|가는))\s?곳(?:이|은|가)?\s?"
                           r"|(?:이주|이사|이민|전입|정착|귀국|귀촌|이전|합가)(?:하신|한|하실|할|하는|하시는|\s?간|\s?가신|\s?가실|\s?온|\s?오신)\s?"
                           r"|(?:계신|계시는|사시는|사는|살던|살고\s?있는|살고\s?계신|거주하는|거주하시는|거주\s?중인|거주\s?중이신|지내는|지내시는|"
                           r"머무는|머무시는|이사\s?간|이사한|이사\s?온|이사\s?갈|이사\s?가는|태어난|자란|나고\s?자란)\s?"
                           r"|(?:본가|친정|시댁|처가|집|댁)(?:이|가)?\s?있는\s?"
                           r"|(?:댁은|댁이|집은|집이)\s?)$")
#: 사람을 가리키는 말(약한 서술을 개인 문맥으로 바꾼다). 같은 절(마침표·물음표·줄바꿈 뒤) 안 어디에 있어도 된다.
#: "저희·우리"는 회사·단체를 가리키는 일이 많아 넣지 않는다("저희 지점은 강남역 근처에"). "저희 아버지"는 "아버지"로 잡힌다.
PERSON_WORD = re.compile(r"(?<![가-힣])(?:저|제가|저는|저도|전|나|난|나는|내가|나도|너|넌|너는|네가|지금|현재|요즘|"
                         r"고객님|선생님|어머니|어머님|아버지|아버님|부모님|엄마|아빠|할머니|할아버지|형|누나|언니|오빠|동생|삼촌|이모|고모|"
                         r"외삼촌|장모님|장인어른|시어머니|시아버지|아내|남편|와이프|아들|딸|친구|여자친구|남자친구|여친|남친|동료|팀원|"
                         r"팀장님|부장님|과장님|대리님|사장님|팀장|부장|과장|대리|사원|직원|신입|신임|후임|전임|가족|조카|사촌|사촌언니|사촌형|"
                         r"처제|처형|시누이|며느리|사위|손자|손녀|지원자|내담자|보호자|피보험자|임차인|후임자|담당자|회원님|본인)"
                         r"(?=$|[\s,]|은|는|이|가|도|께서|님|네|랑|의|한테)")
#: 지명 뒤에 붙으면 시설·기관 위치(일반 언급)다.
FACILITY_AFTER = re.compile(r"^\s?(?:지점|매장|공장|센터|물류|지사|본사|사무소|사업장|캠퍼스|법원|지방법원|지원|검찰|경찰서|세무서|"
                            r"시청|구청|군청|도청|공항|항|터미널|점|날씨|기온|행사|축제|박람회|전시|공연|여행|투어|"
                            r"출장|현장|구간|노선|방면|방향|소재|제철소|창고|협력업체|서비스센터)")
#: 넓은 구역 낱말 — 시설은 아니지만 일반 언급에 흔하다. 앞에 강한 거주 단서가 있으면 개인 문맥으로 본다("거주하시는 김포 구래동 지역").
AREA_AFTER = re.compile(r"^\s?(?:지역|권역|일대|일원)")


#: 지명 뒤에 붙으면 출신 민족·국적·언어("베트남계", "미국인", "일본어")라 지명이 아니다("출신: 베트남계"를 주소로 바꿔 '계'가 샜다).
NOT_PLACE_AFTER = re.compile(r"(?:계|족|어(?![가-힣])|식|풍|산(?![가-힣])|말(?![가-힣])|인(?=$|[\s,.]|이[고며라]|이다|입니|은|는|을|를|의|도|과|와|들|으로|로))")   # .match(text, pos)로 쓴다(^는 pos에서 맞지 않는다)


def _is_predicate(w: str) -> bool:
    """이어 붙이려는 낱말이 서술·단서다("사셔서", "살잖아", "출생으로") — 지명이 아니다."""
    return bool(STRONG_AFTER.match(" " + w) or WEAK_AFTER.match(" " + w) or re.match(r"(?:살|사[셔시세]|지내|계[시셔]|있|없|가[서는]|와서|이사|거주|출생)", w))


def _no_batchim(ch: str) -> bool:
    return "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 == 0


def _candidates(text: str) -> list[tuple[int, int]]:
    spans = []
    for m in LEXICON.finditer(text):
        if NOT_PLACE_AFTER.match(text, m.end()):
            continue
        spans.append((m.start(), m.end()))
    for m in SUFFIX_PLACE.finditer(text):
        w = m.group()
        if w in SUFFIX_STOP or len(w) < 2 or w.endswith("하시") or (w.endswith("시") and _VERB_SI.search(w)):
            continue
        if w.endswith("면") and _no_batchim(w[-2]):   # "세종이시면", "가면" 같은 조건 어미(면 이름은 대개 받침 뒤: 춘양면·김삿갓면)
            continue
        spans.append((m.start(), m.end()))
    spans.sort(key=lambda x: (x[0], -x[1]))
    out: list[list[int]] = []
    for s, e in spans:                       # 겹치면 긴 것, 공백 하나로 붙으면 잇는다("울산 북구", "독일 베를린")
        if out and s < out[-1][1]:
            out[-1][1] = max(out[-1][1], e)
        elif out and text[out[-1][1]:s] == " ":
            out[-1][1] = e
        else:
            out.append([s, e])
    # 목록 지명 뒤의 모르는 동네·섬 이름 한 낱말을 잇는다("수원 영통", "김해 장유에", "완도 노화도에")
    for span in out:
        m = re.match(r" ([가-힣]{2,4}?)" + _AHEAD, text[span[1]:])
        w = m.group(1) if m else ""
        if m and not ABSORB_STOP.match(w) and not FACILITY_AFTER.match(" " + w) and not _is_predicate(w):
            span[1] += m.end()
    return [(s, e) for s, e in out]


def _clause_before(text: str, s: int) -> str:
    start = max(text.rfind(c, 0, s) for c in ".!?\n") + 1
    return text[max(start, s - 40):s]


#: 나라 이름 + "사람·출신"은 국적이다("아빠가 영국 사람이라"). 도시는 그대로 거주·출신으로 본다.
COUNTRIES = set(ABROAD[:ABROAD.index("뉴욕")])
NATIONALITY_AFTER = re.compile(r"^\s?(?:사람|출신|국적|교포|계)")


def is_personal(text: str, s: int, e: int) -> bool:
    after, before = text[e:e + 30], text[max(0, s - 30):s]
    if text[s:e].split()[-1] in COUNTRIES and NATIONALITY_AFTER.match(after):
        return False
    if THING_BEFORE.search(before) or THING_AFTER.match(after):
        return False
    strong_before = bool(STRONG_BEFORE.search(before))
    if FACILITY_AFTER.match(after):
        return False
    if AREA_AFTER.match(after) and not strong_before:
        return False
    if strong_before or STRONG_AFTER.match(after) or FROM_TO.match(after) or GAP_RESIDE.match(after) or TO_MOVE.match(after):
        return True
    if CHANGE_AFTER.match(after) and ADDR_CONTEXT.search(_clause_before(text, s)):
        return True
    if re.match(r"^\s?(?:에|에서)?\s?도착", after) and re.search(r"(?<![가-힣])(?:지금|방금|막|이제|드디어)(?![가-힣])", _clause_before(text, s)):
        return True   # "지금 부산역 도착했어"(현재 위치). "후쿠오카 도착 오전 편"(항공편)은 일반
    if WEAK_AFTER.match(after) and PERSON_WORD.search(_clause_before(text, s)):
        return True
    return False


def personal_regions(text: str) -> list[tuple[int, int]]:
    """개인 문맥 지역 이름 구간 목록."""
    return [(s, e) for s, e in _candidates(text) if is_personal(text, s, e)]


def apply(text: str, spans: list[tuple]) -> list[tuple]:
    """(label, start, end, score) 스팬 목록에 개인 문맥 지역을 주소로 더한다. 겹치는 기존 스팬이 이름·직함 등으로 잘못 붙어 있으면
    주소로 바꾸고, 이미 주소이거나 기관이면 둔다."""
    out = list(spans)
    for s, e in personal_regions(text):
        over = [sp for sp in out if sp[1] < e and s < sp[2]]
        # 기존 스팬이 지명보다 넓으면(지우면 나머지 글자가 샌다: "베트남계", "수원지방법원") 그대로 둔다. 지명 안에 든 스팬은 타입과
        # 상관없이 주소로 바꾼다 — 모델이 개인 문맥 지명에 엉뚱한 타입을 붙인 것이다("해운대"→CRIME, 로컬 점검 11/14).
        if any(sp[1] < s or sp[2] > e for sp in over) or any(sp[0] == "ADDRESS" for sp in over):
            continue
        out = [sp for sp in out if sp not in over]
        out.append(("ADDRESS", s, e, 0.9))
    out.sort(key=lambda sp: sp[1])
    return out
